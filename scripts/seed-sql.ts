// Writes supabase/seed.sql from the starter catalogue in src/lib/catalog/seed.ts.
// Run with: npm run seed:sql

import { writeFileSync } from "node:fs";
import { seedCategories, seedMaterials } from "../src/lib/catalog/seed.ts";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  return `'${String(v).replaceAll("'", "''")}'`;
};

const insert = (table: string, rows: Record<string, unknown>[]) => {
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => q(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (id) do nothing;\n`;
};

const categories = seedCategories.map(({ accent_hex, accent_pattern, ...c }) => c);
const materials = seedMaterials.map(({ images, created_at, ...m }) => m);

const sql = `-- Generated by scripts/seed-sql.ts — do not edit by hand.\n\n${insert("categories", categories)}\n${insert("materials", materials)}`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${categories.length} categories and ${materials.length} materials to supabase/seed.sql`);
